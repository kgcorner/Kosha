describe('StockDetail', () => {
  let http: HttpTestingController;

  beforeEach(async () => {
    localStorage.clear();
    await TestBed.configureTestingModule({
      imports: [StockDetail],
      providers: [
        provideRouter([]),
        provideHttpClient(withInterceptors([errorInterceptor])),
        provideHttpClientTesting(),
      ],
    }).compileComponents();
    http = TestBed.inject(HttpTestingController);
  });

  afterEach(() => {
    http.verify();
    localStorage.clear();
    TestBed.resetTestingModule();
  });

  function button(fixture: { nativeElement: unknown }, label: RegExp): HTMLButtonElement {
    const found = Array.from(
      (fixture.nativeElement as HTMLElement).querySelectorAll('button'),
    ).find((b) => label.test(b.textContent ?? ''));
    if (!found) {
      throw new Error(`No button matching ${label}`);
    }
    return found as HTMLButtonElement;
  }

  async function loaded() {
    const fixture = create();
    http.expectOne('/api/stocks/7').flush(detail());
    await fixture.whenStable();
    fixture.detectChanges();
    return fixture;
  }

  function create(stockId = '7') {
    const fixture = TestBed.createComponent(StockDetail);
    fixture.componentRef.setInput('stockId', stockId);
    fixture.detectChanges();
    return fixture;
  }

  it('loads the stored detail without calling for fundamentals', async () => {
    const fixture = create();
    http.expectOne('/api/stocks/7').flush(detail());
    await fixture.whenStable();
    fixture.detectChanges();

    const text = (fixture.nativeElement as HTMLElement).textContent ?? '';
    expect(text).toContain('Karur Vysya Bank Ltd.');
    expect(text).toContain('ISIN INE036D01028');
    expect(text).toContain('Alpha Small Cap Fund');
    expect(text).toContain('1 / 4');
    expect(text).toContain('25%');
    expect(text).toContain('Removed from');
    expect(text).toContain('Fetch fundamentals');
    http.expectNone((request) => request.url.includes('/fundamentals'));
  });

  it('fetches fundamentals on click and shows sections, freshness and provider errors', async () => {
    const fixture = create();
    http.expectOne('/api/stocks/7').flush(detail());
    await fixture.whenStable();
    fixture.detectChanges();

    const button = Array.from(
      (fixture.nativeElement as HTMLElement).querySelectorAll('button'),
    ).find((b) => b.textContent?.includes('Fetch fundamentals')) as HTMLButtonElement;
    button.click();
    fixture.detectChanges();
    expect(button.disabled).toBe(true);

    http.expectOne('/api/stocks/7/fundamentals').flush(fundamentals());
    await fixture.whenStable();
    fixture.detectChanges();

    const text = (fixture.nativeElement as HTMLElement).textContent ?? '';
    expect(text).toContain('Company profile');
    expect(text).toContain('PE ratio');
    expect(text).toContain('Promoter pledge');
    expect(text).toContain('Stale');
    expect(text).toContain('Tapetide rate limit or daily quota reached');
    expect(text).toContain('1 section(s) fetched from tapetide just now');
    expect(text).toContain('NSE: KARURVYSYA');
    expect(text).toContain('Fetch again');
  });

  it('shows an error for an invalid id without calling the API', async () => {
    const fixture = create('abc');
    await fixture.whenStable();
    fixture.detectChanges();
    expect((fixture.nativeElement as HTMLElement).textContent).toContain('not a valid stock id');
  });

  it('shows the backend error when the stock does not exist', async () => {
    const fixture = create('999');
    http
      .expectOne('/api/stocks/999')
      .flush({ error: 'Stock #999 not found' }, { status: 404, statusText: 'Not Found' });
    await fixture.whenStable();
    fixture.detectChanges();
    const text = (fixture.nativeElement as HTMLElement).textContent ?? '';
    expect(text).toContain('Couldn’t load this stock');
  });
  it('asks for BUY/IGNORE by default and renders the verdict with reasons', async () => {
    const fixture = await loaded();
    button(fixture, /Should I buy\?/).click();
    fixture.detectChanges();

    const request = http.expectOne((r) => r.url === '/api/stocks/7/analysis');
    expect(request.request.params.get('held')).toBe('false');
    expect(request.request.params.has('refresh')).toBe(false);
    request.flush(analysis());
    await fixture.whenStable();
    fixture.detectChanges();

    const text = (fixture.nativeElement as HTMLElement).textContent ?? '';
    expect(text).toContain('BUY');
    expect(text).toContain('medium confidence');
    expect(text).toContain('Broad small-cap fund backing');
    expect(text).toContain('Low promoter pledge');
    expect(text).toContain('What would change this view');
    expect(text).not.toContain('Red flags');
    expect(text).toContain('Older stored data was used for: pledge');
    expect(text).toContain('google/gemini-2.5-flash via openrouter');
    expect(text).toContain('Not investment advice');
    expect((fixture.nativeElement as HTMLElement).querySelector('.verdict--buy')).not.toBeNull();
  });

  it('asks HOLD/SELL when the user holds the stock, remembers it, and re-runs with refresh', async () => {
    const fixture = await loaded();
    const toggle = (fixture.nativeElement as HTMLElement).querySelector(
      '.held-toggle input',
    ) as HTMLInputElement;
    toggle.click();
    fixture.detectChanges();
    expect(localStorage.getItem('kosha.held.7')).toBe('1');

    button(fixture, /Should I hold or sell\?/).click();
    const first = http.expectOne((r) => r.url === '/api/stocks/7/analysis');
    expect(first.request.params.get('held')).toBe('true');
    first.flush(analysis({ held: true, analysis: { ...analysis().analysis, verdict: 'SELL' } }));
    await fixture.whenStable();
    fixture.detectChanges();
    expect((fixture.nativeElement as HTMLElement).querySelector('.verdict--sell')).not.toBeNull();

    button(fixture, /Re-run/).click();
    const rerun = http.expectOne((r) => r.url === '/api/stocks/7/analysis');
    expect(rerun.request.params.get('refresh')).toBe('true');
    expect(rerun.request.params.get('held')).toBe('true');
    rerun.flush(analysis({ held: true, cached: false }));
  });

  it('restores the remembered held flag on load', async () => {
    localStorage.setItem('kosha.held.7', '1');
    const fixture = await loaded();
    expect(button(fixture, /Should I hold or sell\?/)).toBeTruthy();
  });

  it('shows the backend message when no LLM is configured', async () => {
    const fixture = await loaded();
    button(fixture, /Should I buy\?/).click();
    http
      .expectOne((r) => r.url === '/api/stocks/7/analysis')
      .flush(
        {
          error:
            'LLM API key is not set for https://openrouter.ai/api/v1 (e.g. OPENROUTER_API_KEY)',
          code: 'not_configured',
        },
        { status: 503, statusText: 'Service Unavailable' },
      );
    await fixture.whenStable();
    fixture.detectChanges();
    expect((fixture.nativeElement as HTMLElement).textContent).toContain('OPENROUTER_API_KEY');
  });
});
